// Builds decks.js from decks/*.json so the page needs no fetch (it also runs from file://).
// Usage: node tools/build-decks.mjs
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const META = [
  { id: 'geo', name: 'World Geography', blurb: 'Capitals, rivers, straits, superlatives and the odd corner of the map.' },
  { id: 'analysis', name: 'Real Analysis', blurb: 'Sequences, series, continuity, differentiation, integration and uniform convergence.' },
];
const out = [];
for (const m of META) {
  const f = join(root, 'decks', m.id + '.json');
  if (!existsSync(f)) { console.warn('missing', f); continue; }
  const cards = JSON.parse(readFileSync(f, 'utf8'));
  const seen = new Set(), clean = [];
  for (const c of cards) {
    const k = String(c.q).toLowerCase().replace(/[^a-z0-9]+/g, ' ').trim(); if (seen.has(k)) continue; seen.add(k);
    if (c.type === 'mc' && !(Array.isArray(c.choices) && c.choices.includes(c.a))) { console.warn('skip (answer not among choices):', c.q); continue; }
    clean.push({ type: c.type, q: c.q, ...(c.type === 'mc' ? { choices: c.choices } : {}), a: c.a, ...(c.alt && c.alt.length ? { alt: c.alt } : {}), hint: c.hint || '', why: c.why || '', level: c.level || 2, tags: c.tags || [] });
  }
  out.push({ ...m, cards: clean });
  console.log(m.id, clean.length, 'cards');
}
const js = `'use strict';\n// decks.js — built-in study decks. Generated by tools/build-decks.mjs from decks/*.json; edit the JSON, not this file.\nconst DECKS = ${JSON.stringify(out, null, 1)};\n`;
writeFileSync(join(root, 'decks.js'), js);
console.log('wrote decks.js', js.length, 'bytes');
